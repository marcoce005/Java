
public class printf {

    public static void main(String[] args) {
        // the same as C language

        System.out.printf("ciro:\t%d\n", 12);

        System.out.printf("ciro:\t%f\n", 12.0);

        System.out.printf("ciro:\t%.2f\n", 12.0);
        
        System.out.printf("ciro:\t%s\n", "ciro");
        System.out.printf("ciro:\t%50s\n", "ciro");

        System.out.printf("ciro:\t%c\n", 'a');

        System.out.printf("ciro:\t%b\n", 1);
    }
}
